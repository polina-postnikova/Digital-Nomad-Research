def prepare_panel(audit: pd.DataFrame, panel: pd.DataFrame) -> pd.DataFrame:
    """Merge audit treatment information and construct only lagged covariates."""
    p = panel.copy()

    treatment_cols = [
        "iso3", "qualifying", "program_name", "announcement_date",
        "launch_or_effective_date", "announcement_precision",
        "effective_precision", "announcement_date_parsed", "effective_date",
        "adoption_year", "adoption_month", "first_full_exposure_year",
        "calendar_year_exposure", "status_during_observation_period",
        "reason_for_exclusion"
    ]
    treatment_cols = [c for c in treatment_cols if c in audit.columns]

    p = p.merge(audit[treatment_cols], on="iso3", how="left", validate="many_to_one")

    p = p.sort_values(["iso3", "year"]).reset_index(drop=True)

    p["log_gdp"] = np.where(p["gdp"] > 0, np.log(p["gdp"]), np.nan)
    p["log_gdp_lag1"] = p.groupby("iso3")["log_gdp"].shift(1)
    p["inflation_annual_pct_lag1"] = p.groupby("iso3")["inflation_annual_pct"].shift(1)
    p["internet_usage_pct_lag1"] = p.groupby("iso3")["internet_usage_pct"].shift(1)

    return p


def main_sample(
    panel: pd.DataFrame,
    cohort_col: str = "first_full_exposure_year",
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Build the main precision-based sample.

    Treated countries must have:
      * a qualifying program;
      * an effective date with month/day precision;
      * an estimable post-treatment period in the observed panel.

    Countries with no qualifying program are never-treated.
    Countries with missing/ambiguous treatment dates are excluded.
    """
    p = panel.copy()
    max_year = int(p["year"].max())

    precise_treated = (
        p["qualifying"].fillna(False)
        & p[cohort_col].notna()
    )

    country = (
        p.groupby("iso3", as_index=False)
        .agg(
            qualifying=("qualifying", "max"),
            cohort=(cohort_col, "first"),
            effective_precision=("effective_precision", "first"),
            country_name=("country_name", "first"),
        )
    )

    country["is_never_treated"] = ~country["qualifying"].fillna(False)
    country["main_treated"] = (
        country["qualifying"].fillna(False)
        & country["cohort"].notna()
        & (country["cohort"].astype("float") < max_year)
    )


    keep_iso = set(
        country.loc[country["is_never_treated"] | country["main_treated"], "iso3"]
    )

    out = p[p["iso3"].isin(keep_iso)].copy()

    cohort_map = country.set_index("iso3")["cohort"].to_dict()
    out["cohort"] = out["iso3"].map(cohort_map)
    out["treated_main"] = (
        out["cohort"].notna()
        & (out["year"] >= out["cohort"])
    ).astype(int)

    return out, country


def sample_flow(panel: pd.DataFrame, audit: pd.DataFrame, country: pd.DataFrame) -> pd.DataFrame:
    """Return a compact sample-flow table for the paper."""
    all_countries = set(panel["iso3"].dropna().unique())
    qualifying = set(audit.loc[audit["qualifying"], "iso3"])
    precise = set(
        audit.loc[
            audit["qualifying"]
            & audit["effective_precision"].isin(["month", "day"])
            & audit["first_full_exposure_year"].notna(),
            "iso3"
        ]
    )
    never = all_countries - qualifying
    estimable = set(country.loc[country["main_treated"], "iso3"])
    ambiguous = qualifying - precise

    rows = [
        ("Countries in outcome panel", len(all_countries)),
        ("Countries with qualifying visa program", len(qualifying)),
        ("Never-treated countries", len(never)),
        ("Qualifying countries with month/day effective date", len(precise)),
        ("Qualifying countries with ambiguous/missing effective date", len(ambiguous)),
        ("Treated countries with at least one observed full post-treatment year", len(estimable)),
        ("Treatment cohorts supporting the main estimator", int(country.loc[country["main_treated"], "cohort"].nunique())),
    ]
    return pd.DataFrame(rows, columns=["item", "n"])


# Callaway--Sant'Anna-style group-time DID

def cs_group_time(
    data: pd.DataFrame,
    outcome: str = OUTCOME,
    cohort_col: str = "cohort",
) -> pd.DataFrame:
    """
    Unadjusted group-time DID using never-treated countries.

    For cohort g and year t >= g:
      ATT(g,t) =
        mean[Y_i,t - Y_i,g-1 | G_i=g]
        -
        mean[Y_i,t - Y_i,g-1 | never-treated]

    This is the simplest never-treated-control version of the
    Callaway--Sant'Anna group-time estimand. It is deliberately not presented
    as a solution to endogenous treatment adoption.
    """
    d = data.copy()
    d = d.dropna(subset=[outcome, "iso3", "year"])

    country_cohort = (
        d.groupby("iso3")[cohort_col]
        .first()
    )
    never = set(country_cohort[country_cohort.isna()].index)

    if not never:
        raise ValueError("No never-treated countries are available.")

    treated_cohorts = sorted(
        country_cohort.dropna().astype(int).unique().tolist()
    )

    records = []

    for g in treated_cohorts:
        treated_ids = set(country_cohort[country_cohort.eq(g)].index)
        base_year = g - 1

        base = (
            d[d["year"].eq(base_year)][["iso3", outcome]]
            .rename(columns={outcome: "y_base"})
        )

        for t in sorted(d.loc[d["year"].ge(g), "year"].unique()):
            yt = d[d["year"].eq(t)][["iso3", outcome]].rename(
                columns={outcome: "y_t"}
            )

            changes = yt.merge(base, on="iso3", how="inner")
            changes["delta"] = changes["y_t"] - changes["y_base"]

            tr = changes[changes["iso3"].isin(treated_ids)]["delta"].dropna()
            co = changes[changes["iso3"].isin(never)]["delta"].dropna()

            if len(tr) < 1 or len(co) < 2:
                continue

            est = tr.mean() - co.mean()
            var_tr = tr.var(ddof=1) / len(tr) if len(tr) > 1 else np.nan
            var_co = co.var(ddof=1) / len(co)
            se = np.sqrt(var_tr + var_co) if np.isfinite(var_tr) else np.nan

            records.append(
                {
                    "cohort": g,
                    "year": int(t),
                    "event_time": int(t - g),
                    "estimate": est,
                    "se": se,
                    "n_treated": len(tr),
                    "n_never": len(co),
                }
            )

    return pd.DataFrame(records)


def aggregate_event_time(gt: pd.DataFrame) -> pd.DataFrame:
    """Aggregate group-time estimates by event time using treated-country weights."""
    if gt.empty:
        return gt.copy()

    rows = []
    for e, sub in gt.groupby("event_time"):
        w = sub["n_treated"].to_numpy(dtype=float)
        y = sub["estimate"].to_numpy(dtype=float)

        if w.sum() == 0:
            continue

        est = np.average(y, weights=w)

        se = np.sqrt(
            np.average(
                np.square(sub["se"].fillna(0).to_numpy(dtype=float)),
                weights=w,
            )
        ) / np.sqrt(max(len(sub), 1))

        rows.append(
            {
                "event_time": int(e),
                "estimate": est,
                "se": se,
                "ci_low": est - 1.96 * se,
                "ci_high": est + 1.96 * se,
                "n_cohorts": int(sub["cohort"].nunique()),
                "n_treated_country_observations": int(sub["n_treated"].sum()),
            }
        )

    return pd.DataFrame(rows).sort_values("event_time")

# TWFE benchmark

def twfe_benchmark(data: pd.DataFrame, covariates: list[str] | None = None):
    """
    Conventional two-way fixed-effects benchmark.

    Treatment is the main annual first-full-exposure indicator. Country and
    year fixed effects are absorbed with categorical indicators.
    """
    covariates = covariates or BASE_COVARIATES
    d = data.copy()

    cols = [OUTCOME, "treated_main", "iso3", "year"] + covariates
    d = d[cols].dropna().copy()
    d["year"] = d["year"].astype(int)
    d["iso3"] = d["iso3"].astype(str)

    rhs = "treated_main"
    available_covars = [c for c in covariates if c in d.columns and d[c].notna().any()]
    if available_covars:
        rhs += " + " + " + ".join(available_covars)

    formula = f"{OUTCOME} ~ {rhs} + C(iso3) + C(year)"

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        model = smf.ols(formula, data=d).fit(
            cov_type="cluster",
            cov_kwds={"groups": d["iso3"]},
        )

    return model, d

# Semi-synthetic experiment

def exact_date_discrepancies(audit: pd.DataFrame) -> pd.DataFrame:
    """
    Return qualifying countries with both announcement and effective dates
    measured to month/day precision.

    The semi-synthetic experiment uses these observed discrepancies as the
    empirical source of treatment-date error.
    """
    a = audit.copy()

    both = (
        a["qualifying"]
        & a["announcement_date_parsed"].notna()
        & a["effective_date"].notna()
        & a["announcement_precision"].isin(["month", "day"])
        & a["effective_precision"].isin(["month", "day"])
    )

    out = a.loc[
        both,
        [
            "iso3", "announcement_date_parsed", "effective_date",
            "announcement_precision", "effective_precision"
        ]
    ].copy()

    out["announcement_year"] = out["announcement_date_parsed"].dt.year
    out["effective_year"] = out["effective_date"].dt.year

    out["announcement_full_year"] = np.where(
        out["announcement_date_parsed"].dt.month.eq(1),
        out["announcement_year"],
        out["announcement_year"] + 1,
    )
    out["effective_full_year"] = np.where(
        out["effective_date"].dt.month.eq(1),
        out["effective_year"],
        out["effective_year"] + 1,
    )
    out["date_error_years"] = (
        out["announcement_full_year"] - out["effective_full_year"]
    )

    return out


def make_synthetic_panel(
    real_panel: pd.DataFrame,
    true_cohorts: dict[str, int],
    beta: float,
    rng: np.random.Generator,
) -> pd.DataFrame:

    d = real_panel.copy()

    countries = sorted(d["iso3"].dropna().unique())
    years = sorted(d["year"].dropna().astype(int).unique())

    country_fe = {
        c: rng.normal(0.0, 1.5)
        for c in countries
    }
    country_trend = {
        c: rng.normal(0.0, 0.005)
        for c in countries
    }
    year_fe = {
        y: 0.20 * np.sin((y - min(years)) / 2.0)
        for y in years
    }

    gdp_z = (
        d["log_gdp"]
        - d["log_gdp"].groupby(d["year"]).transform("mean")
    )
    gdp_scale = gdp_z.std(skipna=True)
    if not np.isfinite(gdp_scale) or gdp_scale == 0:
        gdp_z = pd.Series(0.0, index=d.index)
    else:
        gdp_z = gdp_z.fillna(0.0) / gdp_scale

    errors = {}
    phi = 0.45
    for c in countries:
        prev = rng.normal(0.0, 0.7)
        for y in years:
            eps = rng.normal(0.0, 0.7)
            prev = phi * prev + eps
            errors[(c, y)] = prev

    y = []
    for idx, row in d.iterrows():
        c = row["iso3"]
        yr = int(row["year"])
        g = true_cohorts.get(c)
        treated = int(g is not None and yr >= g)

        value = (
            5.0
            + country_fe[c]
            + year_fe[yr]
            + country_trend[c] * (yr - min(years))
            + 0.20 * gdp_z.loc[idx]
            + beta * treated
            + errors[(c, yr)]
        )
        y.append(value)

    d["synthetic_unemployment"] = y
    return d


def run_twfe_on_synthetic(
    d: pd.DataFrame,
    cohort_map: dict[str, int],
    use_misdated: bool,
):
    """Estimate TWFE on a synthetic panel using true or misdated treatment."""
    x = d.copy()
    x["year"] = x["year"].astype(int)
    cohort = x["iso3"].map(cohort_map)
    x["synthetic_treat"] = (
        cohort.notna() & x["year"].ge(cohort)
    ).astype(int)

    formula = "synthetic_unemployment ~ synthetic_treat + C(iso3) + C(year)"
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        m = smf.ols(formula, data=x).fit(
            cov_type="cluster",
            cov_kwds={"groups": x["iso3"]},
        )
    return float(m.params["synthetic_treat"]), float(m.bse["synthetic_treat"])


def run_cs_on_synthetic(
    d: pd.DataFrame,
    cohort_map: dict[str, int],
):
    """Run the same never-treated group-time estimator on synthetic outcomes."""
    x = d.copy()
    x["cohort"] = x["iso3"].map(cohort_map)
    x["treated_main"] = (
        x["cohort"].notna() & x["year"].ge(x["cohort"])
    ).astype(int)

    gt = cs_group_time(x, outcome="synthetic_unemployment", cohort_col="cohort")
    if gt.empty:
        return np.nan, np.nan

    post = gt[gt["event_time"] >= 0].copy()
    if post.empty:
        return np.nan, np.nan

    w = post["n_treated"].to_numpy(dtype=float)
    est = np.average(post["estimate"], weights=w)
    se = np.sqrt(
        np.average(
            np.square(post["se"].fillna(0).to_numpy(dtype=float)),
            weights=w,
        )
    ) / np.sqrt(max(len(post), 1))

    return float(est), float(se)


def run_semi_synthetic(
    panel: pd.DataFrame,
    audit: pd.DataFrame,
    beta: float = -1.0,
    reps: int = 200,
    seed: int = 12345,
) -> tuple[pd.DataFrame, pd.DataFrame]:

    discrepancy = exact_date_discrepancies(audit)

    max_year = int(panel["year"].max())
    eff = audit.loc[
        audit["qualifying"]
        & audit["first_full_exposure_year"].notna()
        & (pd.to_numeric(audit["first_full_exposure_year"], errors="coerce") < max_year),
        ["iso3", "first_full_exposure_year"]
    ].copy()

    true_map = dict(
        zip(eff["iso3"], eff["first_full_exposure_year"].astype(int))
    )

    if not true_map:
        raise ValueError("No estimable precise treatment cohorts for simulation.")


    true_map = {
        k: v for k, v in true_map.items()
        if k in set(panel["iso3"])
    }

    ann_all = audit.loc[
        audit["qualifying"]
        & audit["announcement_date_parsed"].notna(),
        ["iso3", "announcement_date_parsed"]
    ].copy()
    ann_all["announcement_cohort"] = ann_all["announcement_date_parsed"].dt.year

    ann_map = dict(
        zip(ann_all["iso3"], ann_all["announcement_cohort"].astype(int))
    )
    ann_map = {k: v for k, v in ann_map.items() if k in true_map}

    discrepancy_map = {
        k: v for k, v in zip(
            discrepancy["iso3"],
            discrepancy["date_error_years"]
        ) if k in true_map
    }

    rng = np.random.default_rng(seed)
    records = []

    for r in range(reps):
        sim = make_synthetic_panel(panel, true_map, beta=beta, rng=rng)

        cs_true, cs_true_se = run_cs_on_synthetic(sim, true_map)
        twfe_true, twfe_true_se = run_twfe_on_synthetic(sim, true_map, False)

        misdated_map = true_map.copy()
        misdated_map.update(ann_map)

        cs_mis, cs_mis_se = run_cs_on_synthetic(sim, misdated_map)
        twfe_mis, twfe_mis_se = run_twfe_on_synthetic(sim, misdated_map, True)

        for estimator, estimate, se, date_definition in [
            ("CS-style", cs_true, cs_true_se, "effective"),
            ("CS-style", cs_mis, cs_mis_se, "announcement/misdated"),
            ("TWFE", twfe_true, twfe_true_se, "effective"),
            ("TWFE", twfe_mis, twfe_mis_se, "announcement/misdated"),
        ]:
            if np.isfinite(estimate):
                records.append(
                    {
                        "rep": r + 1,
                        "estimator": estimator,
                        "date_definition": date_definition,
                        "estimate": estimate,
                        "se": se,
                        "bias": estimate - beta,
                        "covered_95": (
                            np.isfinite(se)
                            and (estimate - 1.96 * se <= beta <= estimate + 1.96 * se)
                        ),
                        "sign_error": np.sign(estimate) != np.sign(beta),
                    }
                )

    results = pd.DataFrame(records)

    summary = (
        results.groupby(["estimator", "date_definition"], as_index=False)
        .agg(
            mean_estimate=("estimate", "mean"),
            mean_bias=("bias", "mean"),
            rmse=("bias", lambda x: float(np.sqrt(np.mean(np.square(x))))),
            coverage_95=("covered_95", "mean"),
            sign_error_rate=("sign_error", "mean"),
            repetitions=("estimate", "size"),
        )
    )

    meta = pd.DataFrame(
        {
            "item": [
                "true_effect",
                "simulation_repetitions",
                "precise_effective_cohorts_used",
                "observed_announcement/effective_discrepancies_used",
            ],
            "value": [
                beta,
                reps,
                len(true_map),
                len(discrepancy_map),
            ],
        }
    )

    return summary, meta


