def parse_date_precision(value: object) -> str:
    """Identify whether an audit date contains year, month, or day precision."""
    if pd.isna(value):
        return "missing"
    s = str(value).strip()
    if re.fullmatch(r"\d{4}", s):
        return "year"
    if re.fullmatch(r"\d{4}[-/]\d{1,2}", s):
        return "month"
    if re.fullmatch(r"\d{1,2}/\d{1,2}/\d{2,4}", s):
        return "day"
    parsed = pd.to_datetime(s, errors="coerce")
    return "day" if pd.notna(parsed) else "other"


def parse_audit_date(value: object) -> pd.Timestamp:
    """Parse audit date values, returning NaT when unavailable."""
    if pd.isna(value):
        return pd.NaT
    return pd.to_datetime(str(value).strip(), errors="coerce")


def build_treatment_variables(audit: pd.DataFrame) -> pd.DataFrame:

    a = audit.copy()

    a["qualifying"] = (
        a["qualifying_program_found"]
        .astype("string")
        .str.lower()
        .eq("yes")
    )

    a["announcement_precision"] = a["announcement_date"].map(parse_date_precision)
    a["effective_precision"] = a["launch_or_effective_date"].map(parse_date_precision)

    a["announcement_date_parsed"] = a["announcement_date"].map(parse_audit_date)
    a["effective_date"] = a["launch_or_effective_date"].map(parse_audit_date)

    a["adoption_year"] = a["effective_date"].dt.year.astype("Int64")
    a["adoption_month"] = a["effective_date"].dt.month.astype("Int64")

    a["first_full_exposure_year"] = pd.Series(pd.NA, index=a.index, dtype="Int64")
    exact = a["qualifying"] & a["effective_date"].notna() & (
        a["effective_precision"].isin(["month", "day"])
    )
    jan = exact & a["adoption_month"].eq(1)
    non_jan = exact & a["adoption_month"].gt(1)

    a.loc[jan, "first_full_exposure_year"] = a.loc[jan, "adoption_year"]
    a.loc[non_jan, "first_full_exposure_year"] = (
        a.loc[non_jan, "adoption_year"] + 1
    )

    a["calendar_year_exposure"] = pd.Series(pd.NA, index=a.index, dtype="Int64")
    known_year = a["qualifying"] & a["adoption_year"].notna()
    a.loc[known_year, "calendar_year_exposure"] = a.loc[known_year, "adoption_year"]

    return a


