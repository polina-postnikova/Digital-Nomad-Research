#
# Design choices (see docstring notes inline):
#   - Okabe-Ito colorblind-safe palette, color paired with marker/linestyle
#     so encoding survives grayscale printing.
#   - Object-oriented Matplotlib API + constrained layout instead of the
#     pyplot global-state calls + tight_layout() (the two layout engines
#     can conflict when mixed).
#   - CI level stated explicitly in the axis label; an interval means
#     nothing without saying what it is.
#   - Any omitted/normalized reference period is drawn as an explicit
#     marker rather than left as an unexplained gap in the line.
#   - The descriptive trajectory plot shows the number of countries behind
#     each point (N), since the panel is unbalanced across event time as
#     cohorts enter, and that was previously invisible.
#   - Exported at 300 dpi with editable SVG text, and plt.show() is called
#     so the figure also renders inline in Colab/Jupyter.

import matplotlib as mpl

# Okabe-Ito colorblind-safe palette (Okabe & Ito, 2008).
COLOR_ESTIMATE = "#0072B2"    # blue
COLOR_CI = "#000000"          # black
COLOR_REFERENCE = "#D55E00"   # vermillion
COLOR_ZERO = "#666666"        # neutral gray, distinct from data color
COLOR_INDIVIDUAL = "#999999"  # light gray for background trajectories
COLOR_COUNT_BARS = "#CCCCCC"  # light gray for N bars

_PLOT_RC = {
    "font.size": 10,
    "axes.titlesize": 12,
    "axes.titleweight": "bold",
    "axes.labelsize": 10,
    "legend.fontsize": 9,
    "svg.fonttype": "none",  # keep SVG text editable/searchable
}


def _apply_base_style(ax: plt.Axes) -> None:
    """Shared axis styling: light y-grid behind the data, no top/right spines."""
    ax.set_axisbelow(True)
    ax.grid(True, axis="y", linewidth=0.5, alpha=0.3, zorder=0)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(direction="out")


def plot_event_study(
    event_df: pd.DataFrame,
    output_path: Path,
    reference_time: float | None = None,
    ci_level: float = 95.0,
) -> None:
    """
    Plot event-time coefficient estimates with confidence intervals.

    reference_time: the omitted/normalized event-time period (e.g. -1), if
    the estimator has one. If it is not present in event_df, it is drawn
    explicitly as a zero-effect marker instead of appearing as an
    unexplained gap. Leave as None if the estimator has no such period.
    ci_level: confidence level of ci_low/ci_high, stated on the axis.
    """
    if event_df.empty:
        return

    output_path = Path(output_path).with_suffix(".svg")

    d = event_df.sort_values("event_time").reset_index(drop=True)
    x = d["event_time"].to_numpy(dtype=float)
    y = d["estimate"].to_numpy(dtype=float)
    lo = d["ci_low"].to_numpy(dtype=float)
    hi = d["ci_high"].to_numpy(dtype=float)

    yerr_low = y - lo
    yerr_high = hi - y
    if np.any(yerr_low < 0) or np.any(yerr_high < 0):
        raise ValueError(
            "ci_low must be <= estimate <= ci_high for every event_time; "
            "found an inverted interval."
        )

    with mpl.rc_context(_PLOT_RC):
        fig, ax = plt.subplots(figsize=(9, 5), layout="constrained")

        ax.axhline(0, color=COLOR_ZERO, linewidth=1, zorder=1)
        ax.axvline(
            -0.5,
            color=COLOR_ZERO,
            linestyle="--",
            linewidth=1,
            zorder=1,
            label="Full exposure begins",
        )

        ax.errorbar(
            x,
            y,
            yerr=[yerr_low, yerr_high],
            fmt="o-",
            color=COLOR_ESTIMATE,
            ecolor=COLOR_CI,
            elinewidth=1,
            capsize=3,
            markersize=5,
            label=f"Estimate ({ci_level:.0f}% CI)",
            zorder=3,
        )

        if reference_time is not None and not np.isclose(x, reference_time).any():
            ax.scatter(
                [reference_time],
                [0],
                marker="D",
                s=40,
                color=COLOR_REFERENCE,
                zorder=4,
                label=f"Reference period (t={reference_time:g}, normalized to 0)",
            )

        ax.set_xlabel("Event time (years relative to first full exposure)")
        ax.set_ylabel(f"Estimated association with visa adoption ({ci_level:.0f}% CI)")
        ax.set_title("Event-Time Associations with Digital-Nomad Visa Adoption")

        tick_lo = x.min() if reference_time is None else min(x.min(), reference_time)
        tick_hi = x.max() if reference_time is None else max(x.max(), reference_time)
        ax.set_xticks(np.arange(np.floor(tick_lo), np.ceil(tick_hi) + 1))

        _apply_base_style(ax)
        ax.legend(frameon=False, loc="best")

        fig.savefig(
            output_path,
            dpi=300,
            facecolor="white",
            metadata={
                "Description": (
                    "Event-study coefficients with confidence intervals. "
                    f"CI level: {ci_level:.0f}%. Vertical dashed line marks "
                    "the start of full exposure."
                )
            },
        )
        plt.show()
        plt.close(fig)


def plot_real_trajectories(
    panel: pd.DataFrame,
    audit: pd.DataFrame,
    output_path: Path,
    max_cohorts: int = 10,
    min_n_countries: int = 3,
) -> None:
    """
    Plot mean unemployment around adoption for a readable descriptive figure.
    This is explicitly descriptive and is not an event-study estimator.

    Because cohorts enter the panel at different calendar years, the number
    of countries behind the mean varies by event_time (the panel is
    unbalanced). That count is plotted on a secondary axis, and points
    supported by fewer than `min_n_countries` are shown with reduced
    emphasis rather than looking as trustworthy as the well-supported
    middle of the series.
    """
    output_path = Path(output_path).with_suffix(".svg")

    d = panel.copy()
    cohort = (
        audit.set_index("iso3")["first_full_exposure_year"]
        .to_dict()
    )
    d["cohort"] = d["iso3"].map(cohort)
    d = d.dropna(subset=["cohort", OUTCOME])

    if d.empty:
        return

    first_cohort_year = d.groupby("iso3")["cohort"].first().dropna().sort_values()
    n_available = first_cohort_year.shape[0]
    eligible = first_cohort_year.index[:max_cohorts]
    d = d[d["iso3"].isin(eligible)].copy()
    d["event_time"] = d["year"] - d["cohort"]

    grouped = d.groupby("event_time")[OUTCOME]
    means = grouped.mean().sort_index()
    counts = grouped.count().reindex(means.index)
    thin = counts.to_numpy() < min_n_countries

    with mpl.rc_context(_PLOT_RC):
        fig, ax = plt.subplots(figsize=(9, 5.5), layout="constrained")

        # Faint individual-country trajectories behind the mean, so the
        # aggregate line doesn't imply more homogeneity than the data has.
        for _, g in d.groupby("iso3"):
            g = g.sort_values("event_time")
            ax.plot(
                g["event_time"],
                g[OUTCOME],
                color=COLOR_INDIVIDUAL,
                linewidth=0.7,
                alpha=0.35,
                zorder=1,
            )

        ax.plot(
            means.index[~thin],
            means.values[~thin],
            marker="o",
            color=COLOR_ESTIMATE,
            linewidth=2,
            zorder=3,
            label=f"Cohort mean (n \u2265 {min_n_countries} countries)",
        )
        if thin.any():
            ax.plot(
                means.index[thin],
                means.values[thin],
                marker="o",
                linestyle="none",
                color=COLOR_ESTIMATE,
                alpha=0.4,
                markeredgecolor=COLOR_REFERENCE,
                markeredgewidth=1.2,
                zorder=3,
                label=f"Mean (n < {min_n_countries} countries)",
            )

        ax.axvline(0, color=COLOR_ZERO, linestyle="--", linewidth=1, zorder=1)

        ax2 = ax.twinx()
        ax2.bar(
            counts.index,
            counts.values,
            width=0.6,
            color=COLOR_COUNT_BARS,
            alpha=0.4,
            zorder=0,
        )
        ax2.set_ylabel("Countries contributing (N)", color="#666666")
        ax2.set_ylim(0, n_available)
        ax2.tick_params(colors="#666666")
        ax2.spines["top"].set_visible(False)
        ax.set_zorder(ax2.get_zorder() + 1)
        ax.patch.set_visible(False)

        ax.set_xlabel("Event time (years relative to first full exposure)")
        ax.set_ylabel("Mean unemployment rate")
        ax.set_title(
            "Descriptive Unemployment Trajectories Around Visa Adoption\n"
            f"(earliest {len(eligible)} of {n_available} adopting countries; "
            "unbalanced panel)"
        )
        _apply_base_style(ax)
        ax.legend(frameon=False, loc="best")

        fig.savefig(
            output_path,
            dpi=300,
            facecolor="white",
            metadata={
                "Description": (
                    "Descriptive (non-causal) mean unemployment by event "
                    f"time. Sample restricted to the earliest {len(eligible)} "
                    f"of {n_available} adopting countries by first-full-"
                    "exposure year; panel is unbalanced, N per point shown "
                    f"on secondary axis; points with n<{min_n_countries} "
                    "are flagged."
                )
            },
        )
        plt.show()
        plt.close(fig)


