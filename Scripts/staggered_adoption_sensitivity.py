def parse_date_precision(value: object) -> str:
    """Identify whether an audit date contains year, month, or day precision."""
    if pd.isna(value):
        return "missing"
    s = str(value).strip()
    if re.fullmatch(r"\d{4}", s):
        return "year"
    if re.fullmatch(r"\d{4}[-/]\d{1,2}", s):
        return "month"
    if re.fullmatch(r"\d{1,2}/\d{1,2}/\d{2,4}", s):
        return "day"
    # Try general parsing, but flag it as non-standard so it is not
    # silently treated as an exact date in the main specification.
    parsed = pd.to_datetime(s, errors="coerce")
    return "day" if pd.notna(parsed) else "other"


def parse_audit_date(value: object) -> pd.Timestamp:
    """Parse audit date values, returning NaT when unavailable."""
    if pd.isna(value):
        return pd.NaT
    return pd.to_datetime(str(value).strip(), errors="coerce")


def build_treatment_variables(audit: pd.DataFrame) -> pd.DataFrame:
    """
    Create exact implementation-date fields and a transparent annual cohort.

    Main annual cohort:
      - exact January implementation -> same calendar year;
      - exact month/day implementation after January -> first full calendar
        year after implementation;
      - year-only effective dates are retained for reporting but excluded from
        the precision-based main estimator because the month is unknown.

    This avoids the old blanket 'month >= 7' rule.
    """
    a = audit.copy()

    a["qualifying"] = (
        a["qualifying_program_found"]
        .astype("string")
        .str.lower()
        .eq("yes")
    )

    a["announcement_precision"] = a["announcement_date"].map(parse_date_precision)
    a["effective_precision"] = a["launch_or_effective_date"].map(parse_date_precision)

    a["announcement_date_parsed"] = a["announcement_date"].map(parse_audit_date)
    a["effective_date"] = a["launch_or_effective_date"].map(parse_audit_date)

    a["adoption_year"] = a["effective_date"].dt.year.astype("Int64")
    a["adoption_month"] = a["effective_date"].dt.month.astype("Int64")

    # First full calendar year of exposure. Exact January = current year;
    # otherwise the next calendar year. Unknown month is NOT guessed.
    a["first_full_exposure_year"] = pd.Series(pd.NA, index=a.index, dtype="Int64")
    exact = a["qualifying"] & a["effective_date"].notna() & (
        a["effective_precision"].isin(["month", "day"])
    )
    jan = exact & a["adoption_month"].eq(1)
    non_jan = exact & a["adoption_month"].gt(1)

    a.loc[jan, "first_full_exposure_year"] = a.loc[jan, "adoption_year"]
    a.loc[non_jan, "first_full_exposure_year"] = (
        a.loc[non_jan, "adoption_year"] + 1
    )

    # A second transparent date definition for sensitivity analysis:
    # treatment begins in the calendar year of implementation.
    a["calendar_year_exposure"] = pd.Series(pd.NA, index=a.index, dtype="Int64")
    known_year = a["qualifying"] & a["adoption_year"].notna()
    a.loc[known_year, "calendar_year_exposure"] = a.loc[known_year, "adoption_year"]

    return a


def load_data(csv_path: Path, xlsx_path: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    audit = pd.read_csv(csv_path)
    panel = pd.read_excel(xlsx_path, sheet_name="tourism_and_macroeconomic_data")

    required_audit = {
        "country", "iso3", "qualifying_program_found",
        "announcement_date", "launch_or_effective_date"
    }
    required_panel = {
        "country_name", "iso3", "year", OUTCOME, "gdp",
        "internet_usage_pct", "inflation_annual_pct"
    }

    missing_audit = required_audit - set(audit.columns)
    missing_panel = required_panel - set(panel.columns)
    if missing_audit:
        raise ValueError(f"Audit file is missing columns: {sorted(missing_audit)}")
    if missing_panel:
        raise ValueError(f"Panel file is missing columns: {sorted(missing_panel)}")

    audit["iso3"] = audit["iso3"].astype("string").str.upper().str.strip()
    audit = audit[audit["iso3"].notna() & audit["iso3"].ne("")].copy()
    panel["iso3"] = panel["iso3"].astype(str).str.upper().str.strip()
    panel["year"] = pd.to_numeric(panel["year"], errors="coerce").astype("Int64")

    if panel["iso3"].duplicated().any():
        # Duplicates by country-year are the relevant integrity check.
        dup = panel.duplicated(["iso3", "year"], keep=False)
        if dup.any():
            raise ValueError(
                "Panel contains duplicate country-year observations. "
                "Resolve these before estimation."
            )

    return build_treatment_variables(audit), panel


def prepare_panel(audit: pd.DataFrame, panel: pd.DataFrame) -> pd.DataFrame:
    """Merge audit treatment information and construct only lagged covariates."""
    p = panel.copy()

    treatment_cols = [
        "iso3", "qualifying", "program_name", "announcement_date",
        "launch_or_effective_date", "announcement_precision",
        "effective_precision", "announcement_date_parsed", "effective_date",
        "adoption_year", "adoption_month", "first_full_exposure_year",
        "calendar_year_exposure", "status_during_observation_period",
        "reason_for_exclusion"
    ]
    treatment_cols = [c for c in treatment_cols if c in audit.columns]

    p = p.merge(audit[treatment_cols], on="iso3", how="left", validate="many_to_one")

    p = p.sort_values(["iso3", "year"]).reset_index(drop=True)

    # Predetermined/lagged covariates only.
    p["log_gdp"] = np.where(p["gdp"] > 0, np.log(p["gdp"]), np.nan)
    p["log_gdp_lag1"] = p.groupby("iso3")["log_gdp"].shift(1)
    p["inflation_annual_pct_lag1"] = p.groupby("iso3")["inflation_annual_pct"].shift(1)
    p["internet_usage_pct_lag1"] = p.groupby("iso3")["internet_usage_pct"].shift(1)

    return p


def main_sample(
    panel: pd.DataFrame,
    cohort_col: str = "first_full_exposure_year",
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Build the main precision-based sample.

    Treated countries must have:
      * a qualifying program;
      * an effective date with month/day precision;
      * an estimable post-treatment period in the observed panel.

    Countries with no qualifying program are never-treated.
    Countries with missing/ambiguous treatment dates are excluded.
    """
    p = panel.copy()
    max_year = int(p["year"].max())

    precise_treated = (
        p["qualifying"].fillna(False)
        & p[cohort_col].notna()
    )

    # Country-level treatment status.
    country = (
        p.groupby("iso3", as_index=False)
        .agg(
            qualifying=("qualifying", "max"),
            cohort=(cohort_col, "first"),
            effective_precision=("effective_precision", "first"),
            country_name=("country_name", "first"),
        )
    )

    country["is_never_treated"] = ~country["qualifying"].fillna(False)
    country["main_treated"] = (
        country["qualifying"].fillna(False)
        & country["cohort"].notna()
        & (country["cohort"].astype("float") < max_year)
    )

    # Keep never-treated and treated countries with at least one full
    # post-treatment year observed.
    keep_iso = set(
        country.loc[country["is_never_treated"] | country["main_treated"], "iso3"]
    )

    out = p[p["iso3"].isin(keep_iso)].copy()

    # Main treatment indicator: first full exposure year onward.
    cohort_map = country.set_index("iso3")["cohort"].to_dict()
    out["cohort"] = out["iso3"].map(cohort_map)
    out["treated_main"] = (
        out["cohort"].notna()
        & (out["year"] >= out["cohort"])
    ).astype(int)

    return out, country


def sample_flow(panel: pd.DataFrame, audit: pd.DataFrame, country: pd.DataFrame) -> pd.DataFrame:
    """Return a compact sample-flow table for the paper."""
    all_countries = set(panel["iso3"].dropna().unique())
    qualifying = set(audit.loc[audit["qualifying"], "iso3"])
    precise = set(
        audit.loc[
            audit["qualifying"]
            & audit["effective_precision"].isin(["month", "day"])
            & audit["first_full_exposure_year"].notna(),
            "iso3"
        ]
    )
    never = all_countries - qualifying
    estimable = set(country.loc[country["main_treated"], "iso3"])
    ambiguous = qualifying - precise

    rows = [
        ("Countries in outcome panel", len(all_countries)),
        ("Countries with qualifying visa program", len(qualifying)),
        ("Never-treated countries", len(never)),
        ("Qualifying countries with month/day effective date", len(precise)),
        ("Qualifying countries with ambiguous/missing effective date", len(ambiguous)),
        ("Treated countries with at least one observed full post-treatment year", len(estimable)),
        ("Treatment cohorts supporting the main estimator", int(country.loc[country["main_treated"], "cohort"].nunique())),
    ]
    return pd.DataFrame(rows, columns=["item", "n"])


# ---------------------------------------------------------------------
# Callaway--Sant'Anna-style group-time DID
# ---------------------------------------------------------------------

def cs_group_time(
    data: pd.DataFrame,
    outcome: str = OUTCOME,
    cohort_col: str = "cohort",
) -> pd.DataFrame:
    """
    Unadjusted group-time DID using never-treated countries.

    For cohort g and year t >= g:
      ATT(g,t) =
        mean[Y_i,t - Y_i,g-1 | G_i=g]
        -
        mean[Y_i,t - Y_i,g-1 | never-treated]

    This is the simplest never-treated-control version of the
    Callaway--Sant'Anna group-time estimand. It is deliberately not presented
    as a solution to endogenous treatment adoption.
    """
    d = data.copy()
    d = d.dropna(subset=[outcome, "iso3", "year"])

    country_cohort = (
        d.groupby("iso3")[cohort_col]
        .first()
    )
    never = set(country_cohort[country_cohort.isna()].index)

    if not never:
        raise ValueError("No never-treated countries are available.")

    treated_cohorts = sorted(
        country_cohort.dropna().astype(int).unique().tolist()
    )

    records = []

    for g in treated_cohorts:
        treated_ids = set(country_cohort[country_cohort.eq(g)].index)
        base_year = g - 1

        # Need the pre-treatment outcome for every country contributing to the
        # relevant contrast.
        base = (
            d[d["year"].eq(base_year)][["iso3", outcome]]
            .rename(columns={outcome: "y_base"})
        )

        for t in sorted(d.loc[d["year"].ge(g), "year"].unique()):
            yt = d[d["year"].eq(t)][["iso3", outcome]].rename(
                columns={outcome: "y_t"}
            )

            changes = yt.merge(base, on="iso3", how="inner")
            changes["delta"] = changes["y_t"] - changes["y_base"]

            tr = changes[changes["iso3"].isin(treated_ids)]["delta"].dropna()
            co = changes[changes["iso3"].isin(never)]["delta"].dropna()

            if len(tr) < 1 or len(co) < 2:
                continue

            est = tr.mean() - co.mean()
            var_tr = tr.var(ddof=1) / len(tr) if len(tr) > 1 else np.nan
            var_co = co.var(ddof=1) / len(co)
            se = np.sqrt(var_tr + var_co) if np.isfinite(var_tr) else np.nan

            records.append(
                {
                    "cohort": g,
                    "year": int(t),
                    "event_time": int(t - g),
                    "estimate": est,
                    "se": se,
                    "n_treated": len(tr),
                    "n_never": len(co),
                }
            )

    return pd.DataFrame(records)


def aggregate_event_time(gt: pd.DataFrame) -> pd.DataFrame:
    """Aggregate group-time estimates by event time using treated-country weights."""
    if gt.empty:
        return gt.copy()

    rows = []
    for e, sub in gt.groupby("event_time"):
        w = sub["n_treated"].to_numpy(dtype=float)
        y = sub["estimate"].to_numpy(dtype=float)

        if w.sum() == 0:
            continue

        est = np.average(y, weights=w)

        # A transparent heterogeneity-weighted standard error approximation.
        # The script reports this as an aggregation SE, not a causal inference
        # guarantee.
        se = np.sqrt(
            np.average(
                np.square(sub["se"].fillna(0).to_numpy(dtype=float)),
                weights=w,
            )
        ) / np.sqrt(max(len(sub), 1))

        rows.append(
            {
                "event_time": int(e),
                "estimate": est,
                "se": se,
                "ci_low": est - 1.96 * se,
                "ci_high": est + 1.96 * se,
                "n_cohorts": int(sub["cohort"].nunique()),
                "n_treated_country_observations": int(sub["n_treated"].sum()),
            }
        )

    return pd.DataFrame(rows).sort_values("event_time")


