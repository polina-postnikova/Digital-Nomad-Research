def main() -> None:
    parser = argparse.ArgumentParser(
        description="Professor-aligned staggered-adoption sensitivity analysis."
    )
    parser.add_argument("--audit", default=DEFAULT_CSV)
    parser.add_argument("--panel", default=DEFAULT_XLSX)
    parser.add_argument("--output-dir", default="results_dnm_sensitivity")
    parser.add_argument("--sim-reps", type=int, default=200)
    parser.add_argument("--sim-beta", type=float, default=-1.0)
    parser.add_argument("--seed", type=int, default=12345)
    args, _ = parser.parse_known_args()

    audit_path = Path(args.audit)
    panel_path = Path(args.panel)
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    audit, panel_raw = load_data(audit_path, panel_path)
    panel = prepare_panel(audit, panel_raw)

    # -------------------------------------------------------------
    # 1. Sample flow
    # -------------------------------------------------------------
    main_panel, country = main_sample(panel)
    flow = sample_flow(panel, audit, country)

    audit.to_csv(out / "audit_with_treatment_dates.csv", index=False)
    flow.to_csv(out / "sample_flow.csv", index=False)

    # -------------------------------------------------------------
    # 2. Main CS-style group-time associations
    # -------------------------------------------------------------
    gt = cs_group_time(main_panel, outcome=OUTCOME, cohort_col="cohort")
    event = aggregate_event_time(gt)

    gt.to_csv(out / "cs_group_time_associations.csv", index=False)
    event.to_csv(out / "cs_event_time_associations.csv", index=False)

    # -------------------------------------------------------------
    # 3. TWFE benchmark
    # -------------------------------------------------------------
    twfe_model, twfe_data = twfe_benchmark(main_panel, BASE_COVARIATES)

    twfe_table = pd.DataFrame(
        {
            "term": ["treated_main"],
            "estimate": [twfe_model.params.get("treated_main", np.nan)],
            "se": [twfe_model.bse.get("treated_main", np.nan)],
            "p_value": [twfe_model.pvalues.get("treated_main", np.nan)],
            "ci_low": [
                twfe_model.conf_int().loc["treated_main", 0]
                if "treated_main" in twfe_model.params else np.nan
            ],
            "ci_high": [
                twfe_model.conf_int().loc["treated_main", 1]
                if "treated_main" in twfe_model.params else np.nan
            ],
            "n_obs": [int(twfe_model.nobs)],
            "n_countries": [twfe_data["iso3"].nunique()],
        }
    )
    twfe_table.to_csv(out / "twfe_benchmark.csv", index=False)

    # -------------------------------------------------------------
    # 4. Date sensitivity: calendar-year implementation vs first
    #    full exposure year
    # -------------------------------------------------------------
    sensitivity_country = (
        panel.groupby("iso3", as_index=False)
        .agg(
            qualifying=("qualifying", "max"),
            full_exposure_year=("first_full_exposure_year", "first"),
            calendar_exposure_year=("calendar_year_exposure", "first"),
        )
    )
    sensitivity_country.to_csv(
        out / "treatment_date_sensitivity_country_level.csv",
        index=False,
    )

    # -------------------------------------------------------------
    # 5. Semi-synthetic experiment
    # -------------------------------------------------------------
    sim_summary, sim_meta = run_semi_synthetic(
        panel=panel,
        audit=audit,
        beta=args.sim_beta,
        reps=args.sim_reps,
        seed=args.seed,
    )
    sim_summary.to_csv(out / "semi_synthetic_summary.csv", index=False)
    sim_meta.to_csv(out / "semi_synthetic_metadata.csv", index=False)

    # -------------------------------------------------------------
    # 6. Descriptive real-data dynamics
    # -------------------------------------------------------------
    plot_event_study(
        event,
        out / "event_time_associations.svg",
    )
    plot_real_trajectories(
        panel,
        audit,
        out / "descriptive_unemployment_trajectories.svg",
    )

    # Save the analysis-ready panel.
    main_panel.to_csv(out / "analysis_panel_main.csv", index=False)

    # -------------------------------------------------------------
    # 7. Console summary
    # -------------------------------------------------------------
    print("\n=== Digital Nomad Visa Sensitivity Analysis ===")
    print("\nSample flow:")
    print(flow.to_string(index=False))

    print("\nCS-style event-time associations:")
    if event.empty:
        print("No estimable group-time/event-time estimates.")
    else:
        print(event.to_string(index=False))

    print("\nTWFE benchmark:")
    print(twfe_table.to_string(index=False))

    print("\nSemi-synthetic experiment:")
    print(sim_summary.to_string(index=False))

    print(f"\nResults written to: {out.resolve()}")


if __name__ == "__main__":
    main()
